"""FFmpeg render engine — burns the SAME ASS file the browser preview uses.

Parity guarantee (user requirement: preview == MP4 result):
  preview  : browser canvas renders words+style with rules mirroring libass
  render   : ffmpeg -vf ass=captions.ass on a 1080x1920 canvas
The ASS file is generated by app/subtitles.py from the same CaptionStyle JSON
the frontend sends, so parameters cannot drift between preview and result.

Face tracking (port sederhana dari OpenShorts TRACK mode):
  - Analisis pass di Python: sampling frame tiap N frame di resolusi rendah,
    deteksi posisi "subject" via deteksi gerak + deteksi wajah sederhana
    (gradient-based Viola-Jones via OpenCV kalau tersedia; fallback: centroid
    gerak). Kamera virtual smooth (safe-zone + pan speed) seperti
    SmoothedCameraman OpenShorts.
  - Render pass: crop dinamis via ffmpeg sendcmd + crop filter.
"""

from __future__ import annotations

import os
import json
import math
import shutil
import subprocess
import tempfile
from typing import Any, Optional

import numpy as np
import cv2
import mediapipe as mp

ASPECT = 9 / 16
ANALYSIS_WIDTH = 320          # low-res analysis pass
DETECT_STRIDE = 5             # analyze every Nth frame
SAFE_ZONE_FRACTION = 0.22
PAN_SPEED_FAST = 18.0
PAN_SPEED_SLOW = 4.0

# MediaPipe BlazeFace setup (OpenShorts style) - legacy API (mediapipe 0.10)
mp_face_detection = mp.solutions.face_detection
_face_detector = mp_face_detection.FaceDetection(model_selection=1, min_detection_confidence=0.5)


def run_ffmpeg(cmd: list[str], *, timeout: int | None = None, nice: int = 10):
    """Jalankan ffmpeg dengan prioritas RENDAH (nice+ionice).

    Tanpa ini ffmpeg menyita CPU/IO → web server ikut lag & halaman blank
    beberapa detik saat user menekan Unduh. nice=10 + ionice best-effort 7
    membuat kernel selalu mengutamakan proses web/API.
    """
    prefix: list[str] = []
    if shutil.which("nice"):
        prefix += ["nice", "-n", str(nice)]
    if shutil.which("ionice"):
        prefix += ["ionice", "-c", "2", "-n", "7"]
    kwargs: dict[str, Any] = {"check": True, "capture_output": True}
    if timeout:
        kwargs["timeout"] = timeout
    return subprocess.run(prefix + cmd, **kwargs)


def run_ffmpeg_progress(cmd: list[str], total_seconds: float,
                        on_progress, *, timeout: int | None = None,
                        nice: int = 10) -> None:
    """Jalankan ffmpeg sambil melaporkan kemajuan NYATA (0-100).

    ffmpeg diberi `-progress pipe:1 -nostats`, lalu baris `out_time_us=` dibaca
    dan dibandingkan dengan durasi keluaran yang diharapkan. Ini kemajuan
    sungguhan dari encoder — bukan animasi palsu berbasis waktu tunggu.
    """
    prefix: list[str] = []
    if shutil.which("nice"):
        prefix += ["nice", "-n", str(nice)]
    if shutil.which("ionice"):
        prefix += ["ionice", "-c", "2", "-n", "7"]
    full = prefix + cmd[:1] + ["-progress", "pipe:1", "-nostats"] + cmd[1:]
    proc = subprocess.Popen(full, stdout=subprocess.PIPE,
                            stderr=subprocess.PIPE, text=True, bufsize=1)
    total = max(0.1, float(total_seconds))
    try:
        for line in proc.stdout or []:
            line = line.strip()
            if line.startswith("out_time_us=") or line.startswith("out_time_ms="):
                try:
                    raw = float(line.split("=", 1)[1])
                except ValueError:
                    continue
                # out_time_us dalam mikrodetik; out_time_ms ffmpeg juga mikrodetik
                secs = raw / 1_000_000.0
                pct = max(0, min(99, int(secs / total * 100)))
                try:
                    on_progress(pct)
                except Exception:
                    pass
            elif line == "progress=end":
                try:
                    on_progress(100)
                except Exception:
                    pass
    finally:
        err = (proc.stderr.read() if proc.stderr else "") or ""
        rc = proc.wait(timeout=timeout)
    if rc != 0:
        raise subprocess.CalledProcessError(rc, full, stderr=err[-4000:])


def probe_duration(path: str) -> float:
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "json", path],
        capture_output=True, text=True, check=True,
    ).stdout
    return float(json.loads(out)["format"]["duration"])


def render_preview(
    src: str,
    start: float,
    end: float,
    out_path: str,
    width: int = 360,
    height: int = 640,
    max_seconds: float = 12.0,
) -> str:
    """Fitur-nya kecil + super cepat (VPS, ditanggung server).

    Bikin klip preview resolusi rendah (360x640) tanpa burn karaoke —
    cukup potong + crop 9:16 + transkode cepat. Dipakai browser supaya
    preview editor muncul INSTAN (file kecil, bukan stream 43MB sumber).
    Durasi di-cap (max_seconds) supaya render cepat & file kecil.
    """
    duration = min(end - start, max_seconds)
    probe = subprocess.run(
        ["ffprobe", "-v", "error", "-select_streams", "v:0",
         "-show_entries", "stream=width,height", "-of", "json", src],
        capture_output=True, text=True,
    )
    src_w, src_h = 1080, 1920
    if probe.returncode == 0:
        try:
            d = json.loads(probe.stdout)["streams"][0]
            src_w, src_h = int(d["width"]), int(d["height"])
        except Exception:
            pass

    aspect = width / height
    # center crop to 9:16
    if src_w / src_h > aspect:
        vf = f"crop=w={int(src_h * aspect)}:h={src_h}:x=(iw-ow)/2:y=0,scale={width}:{height}"
    else:
        vf = f"crop=w={src_w}:h={int(src_w / aspect)}:x=0:y=(ih-oh)/2,scale={width}:{height}"

    cmd = [
        "ffmpeg", "-y", "-v", "error",
        "-ss", f"{start:.3f}", "-t", f"{duration:.3f}", "-i", src,
        "-vf", vf,
        "-c:v", "libx264", "-preset", "ultrafast", "-crf", "26",
        "-pix_fmt", "yuv420p",
        "-an",
        "-movflags", "+faststart",
        out_path,
    ]
    run_ffmpeg(cmd)
    return out_path


def probe_size(path: str) -> tuple[int, int]:
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-select_streams", "v:0",
         "-show_entries", "stream=width,height", "-of", "json", path],
        capture_output=True, text=True, check=True,
    ).stdout
    data = json.loads(out)["streams"][0]
    return int(data["width"]), int(data["height"])


