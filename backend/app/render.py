def smooth_camera(
    current: float, target: float, crop_width: float, video_width: float,
    fast: float = PAN_SPEED_FAST, slow: float = PAN_SPEED_SLOW,
) -> float:
    diff = target - current
    safe = crop_width * SAFE_ZONE_FRACTION
    if abs(diff) <= safe:
        return current
    direction = 1.0 if diff > 0 else -1.0
    speed = fast if abs(diff) > crop_width * 0.5 else slow
    new = current + direction * speed
    half = crop_width / 2
    new = max(half, min(video_width - half, new))
    new_diff = target - new
    if (direction == 1 and new_diff < 0) or (direction == -1 and new_diff > 0):
        new = target
    return new


def analyze_speaker_track(src: str, start: float, end: float,
                          on_progress=None) -> dict[str, Any]:
    """Trajektori kamera yang SELALU terpusat pada wajah orang yang bicara.

    Implementasi ada di app/speaker_*.py (dipisah supaya tiap bagian bisa
    diuji sendiri). Ringkasnya:
      - FaceMesh (bukan BlazeFace) memberi landmark bibir sampai 10 wajah, jadi
        BUKAAN MULUT terukur langsung; statistik piksel gagal memisahkan yang
        bicara dari yang diam (rasio tetap ~1.0) karena gerak kepala mendominasi;
      - skor bicara = simpangan bukaan mulut dalam jendela 1 detik, diambil pada
        15 fps karena bicara 3-4 suku kata/detik (5 fps teraliasing);
      - asosiasi identitas memakai ambang relatif LEBAR WAJAH + global-greedy,
        jadi dua orang yang duduk berdempetan tidak tertukar identitas;
      - wajah kecil di latar tidak dianggap kandidat (klip >5 orang tetap jelas);
      - setiap pergantian orang menjadi POTONGAN dan penghalusan dilakukan per
        segmen, sehingga kamera tidak pernah berhenti di ruang kosong antara
        dua wajah;
      - kalau tidak ada yang bicara, kamera bertahan pada orang terakhir;
      - STABILIZER: kamera adalah massa berpegas teredam kritis dengan zona mati,
        jadi kepala yang bergerak kecil tidak menggoyang bingkai sementara
        perpindahan besar tetap diikuti halus (lihat speaker_pick.build_trajectory).
    """
    from .speaker_analyze import analyze as analyze_mesh
    # Mesin utama: YuNet + ByteTrack + Kalman (lihat face_pipeline.py). Recall
    # terukur 100% vs 85% FaceMesh pada podcast uji, dan memberi landmark mata
    # untuk meluruskan kemiringan. FaceMesh tetap jadi cadangan kalau bobot ONNX
    # hilang — face tracking tidak boleh mati hanya karena satu berkas model.
    try:
        from . import face_yunet
        if face_yunet.available():
            from .face_pipeline import analyze as analyze_yunet
            out = analyze_yunet(src, start, end, probe_size=probe_size,
                                run_ffmpeg=run_ffmpeg, aspect=ASPECT,
                                on_progress=on_progress)
            if out.get("trajectory"):
                return out
            print("[face-track] YuNet tidak menghasilkan jalur → coba FaceMesh")
        else:
            print("[face-track] bobot YuNet tidak ada → FaceMesh")
    except Exception as exc:
        import traceback
        print(f"[face-track] pipeline YuNet gagal: {exc.__class__.__name__}: {exc}")
        traceback.print_exc()
    return analyze_mesh(src, start, end, probe_size=probe_size,
                        run_ffmpeg=run_ffmpeg, aspect=ASPECT,
                        on_progress=on_progress)


def analyze_face_track(src: str, start: float, end: float) -> list[float]:
    """Trajektori kamera (kompatibel lama) — kini memakai speaker tracking."""
