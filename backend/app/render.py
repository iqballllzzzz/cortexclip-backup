def render_clip(
    src: str,
    start: float,
    end: float,
    ass_path: Optional[str],
    out_path: str,
    resolution: str = "1080x1920",
    face_tracking: bool = True,
    camera_trajectory: Optional[list[float]] = None,
    camera_cuts: Optional[list[int]] = None,
    camera_fps: float = 15.0,
    camera_rolls: Optional[list[float]] = None,
    watermark: bool = True,
    icon_ass_path: Optional[str] = None,
    icon_png_overlays: Optional[list[dict[str, Any]]] = None,
    broll_video_overlays: Optional[list[dict[str, Any]]] = None,
) -> str:
    """Cut + reframe + burn subtitles (+ ikon overlay) -> vertical MP4.

    Resolution choices: 1080x1920, 720x1280, 1080x1080.
    watermark: bakar watermark CortexClipAI (default ON — dihapus hanya
    setelah user menonton 4 iklan, via flag dari render_clip.py).
    icon_ass_path: ASS overlay ikon/b-roll (layer terpisah dari subtitle).
    """
    w, h = map(int, resolution.split("x"))
    aspect = w / h
    src_w, src_h = probe_size(src)

    # watermark PNG komposit (logo+nama+tagline) — skala ke lebar output
    wm_path = None
    if watermark:
        try:
            from .watermark import build_watermark_png
            wm_path = build_watermark_png(target_width=w)
        except Exception:
            wm_path = None

    # already vertical-ish? pass through crop centered
    filters: list[str] = []
    vf_parts: list[str] = []

    if face_tracking and camera_trajectory and len(camera_trajectory) > 1:
        cmdfile = build_sendcmd_file(camera_trajectory, src_w, src_h,
                                     analysis_fps=camera_fps, cuts=camera_cuts,
                                     rolls=camera_rolls)
        crop_w = min(int(src_h * aspect), src_w)
        # dynamic crop with sendcmd-driven x
        vf_parts.append(f"sendcmd=f={cmdfile}")
        # AFFINE DEROLL: rotate diletakkan SEBELUM crop supaya yang diputar
        # adalah frame penuh — memutar setelah crop akan memasukkan sudut hitam
        # ke dalam bingkai. Rotasi memakai piksel dari luar jendela crop, jadi
        # tidak ada tepi kosong selama sudutnya kecil (dibatasi 12 derajat).
        if camera_rolls:
            vf_parts.append("rotate=a=0:c=none:ow=iw:oh=ih:bilinear=1")
        vf_parts.append(f"crop=w={crop_w}:h={src_h}:x=0:y=0")
    else:
        # center crop to target aspect
        if src_w / src_h > aspect:
            crop_w = int(src_h * aspect)
            vf_parts.append(f"crop=w={crop_w}:h={src_h}:x=(iw-ow)/2:y=0")
        else:
            crop_h = int(src_w / aspect)
            vf_parts.append(f"crop=w={src_w}:h={crop_h}:x=0:y=(ih-oh)/2")

    # scale to delivery size (never downscale below source quality needlessly)
    vf_parts.append(f"scale={w}:{h}:force_original_aspect_ratio=increase")
    vf_parts.append(f"crop={w}:{h}")

    from .subtitles import fonts_dir as subtitle_fonts_dir
    fonts_dir = subtitle_fonts_dir()

    def ass_filter(p: str) -> str:
        esc = p.replace("\\", "/").replace(":", "\\:").replace("'", "\\'")
        return f"ass='{esc}':fontsdir='{fonts_dir}'"

    if ass_path:
        vf_parts.append(ass_filter(ass_path))
    if icon_ass_path:
        vf_parts.append(ass_filter(icon_ass_path))

    # --- ikon & b-roll: overlay PNG per placement (Twemoji pre-render) ---
    # ASS emoji tidak andal (libass+CBDT/COLRv1 blank di beberapa build);
    # PNG overlay 100% konsisten antar mesin.
    png_overlays: list[dict[str, Any]] = []
    if icon_png_overlays:
        png_overlays = icon_png_overlays

    # --- watermark overlay (kiri-atas, offset dari pojok biar terbaca) ---
    cmd = [
        "ffmpeg", "-y", "-v", "error",
        "-ss", f"{start:.3f}", "-t", f"{end - start:.3f}", "-i", src,
    ]

    # bangun filter_complex bertingkat: [vbase] → overlay PNG → watermark → [vout]
    fc_parts: list[str] = []
    cur = "0:v"
    fc_head = f"{','.join(vf_parts)}" if vf_parts else "null"
    fc_parts.append(f"[{cur}]{fc_head}[vbase]")
    cur = "vbase"
    input_idx = 1
    clip_dur = max(0.2, float(end) - float(start))

    # --- B-ROLL VIDEO: PiP di atas video utama (mirror preview <video> PiP) ---
    # Muncul di jendela membulat area atas; audio b-roll dibuang (hanya visual).
    for bv in (broll_video_overlays or []):
        path = bv.get("file")
        if not path or not os.path.exists(path):
            continue
        ts = max(0.0, float(bv.get("t_start", 0)))
        te = min(clip_dur, float(bv.get("t_end", ts + 2.5)))
        if te - ts < 0.3:
            continue
        bw = int(bv.get("width", int(w * 0.78)))
        bh = int(bv.get("height", int(bw * 9 / 16)))
        bx = int(bv.get("x", (w - bw) // 2))
        by = int(bv.get("y", int(h * 0.14)))
        fade_d = min(0.3, max(0.1, (te - ts) / 4.0))
        # loop b-roll biar cukup panjang, mulai dari 0, dipotong ke durasi tampil
        cmd += ["-stream_loop", "-1", "-t", f"{te - ts:.3f}", "-i", path]
        fc_parts.append(
            f"[{input_idx}:v]scale={bw}:{bh}:force_original_aspect_ratio=increase,"
            f"crop={bw}:{bh},setsar=1,format=rgba,"
            f"fade=t=in:st=0:d={fade_d:.2f}:alpha=1,"
            f"fade=t=out:st={max(0.0, (te - ts) - fade_d):.2f}:d={fade_d:.2f}:alpha=1,"
            f"setpts=PTS-STARTPTS+{ts:.3f}/TB[brl{input_idx}]"
        )
        fc_parts.append(
            f"[{cur}][brl{input_idx}]overlay=x={bx}:y={by}:"
            f"eof_action=pass:enable='between(t,{ts:.2f},{te:.2f})'[vb{input_idx}]"
        )
        cur = f"vb{input_idx}"
        input_idx += 1

    # ikon & b-roll PNG: fade in/out + slide masuk (mirror transisi CSS preview).
    # x/y dari caller = TITIK TENGAH ikon (mirror translate(-50%,-50%) preview).
    for ov in png_overlays:
        size = int(ov.get("size", int(w * 0.20)))
        cx = int(ov.get("x", int(w * 0.62)))
        cy = int(ov.get("y", int(h * 0.30)))
        px = cx - size // 2
        py = cy - size // 2
        ts = max(0.0, float(ov.get("t_start", 0)))
        te = min(clip_dur, float(ov.get("t_end", ts + 2.5)))
        if te <= ts:
            continue
        fade_d = min(0.28, max(0.08, (te - ts) / 3.0))
        fade_out_st = max(ts + 0.02, te - fade_d)
        # -loop 1 -t: PNG jadi stream berdurasi klip → filter fade (timeline) jalan
        cmd += ["-loop", "1", "-t", f"{clip_dur:.3f}", "-i", ov["png"]]
        fc_parts.append(
            f"[{input_idx}:v]scale={size}:-1,format=rgba,"
            f"fade=t=in:st={ts:.2f}:d={fade_d:.2f}:alpha=1,"
            f"fade=t=out:st={fade_out_st:.2f}:d={fade_d:.2f}:alpha=1[ico{input_idx}]"
        )
        # slide masuk 0.35s: posisi awal offset → posisi final (ease linear)
        anim = str(ov.get("anim") or "")
        xe, ye = str(px), str(py)
        if anim in ("slide-left", "slide-right", "slide-up", "slide-down"):
            k = f"max(0,1-(t-{ts:.2f})/0.35)"
            dist = int(w * 0.35)
            if anim == "slide-left":
                xe = f"'{px}+{dist}*{k}'"
            elif anim == "slide-right":
                xe = f"'{px}-{dist}*{k}'"
            elif anim == "slide-up":
                ye = f"'{py}+{dist}*{k}'"
            else:
                ye = f"'{py}-{dist}*{k}'"
        fc_parts.append(
            f"[{cur}][ico{input_idx}]overlay=x={xe}:y={ye}:"
            f"enable='between(t,{ts:.2f},{te:.2f})'[vo{input_idx}]"
        )
        cur = f"vo{input_idx}"
        input_idx += 1

    if wm_path:
        x = int(w * 0.055)
        y = int(h * 0.045)
        # 0.30 → 0.52: watermark ~1.7x lebih besar & sekarang setara blok
        # watermark preview editor (logo 9.5% + teks tagline ≈ 50% lebar).
        wm_w = int(w * 0.52)
        cmd += ["-i", wm_path]
        fc_parts.append(f"[{input_idx}:v]scale={wm_w}:-1[wm]")
        fc_parts.append(f"[{cur}][wm]overlay={x}:{y}:format=auto[vout]")
        cmd += ["-filter_complex", ";".join(fc_parts), "-map", "[vout]", "-map", "0:a?"]
    else:
        if png_overlays or (broll_video_overlays or []):
            fc_parts.append(f"[{cur}]null[vout]")
            cmd += ["-filter_complex", ";".join(fc_parts), "-map", "[vout]", "-map", "0:a?"]
        else:
            cmd += ["-vf", ",".join(vf_parts)] if vf_parts else ["-vf", "null"]

    cmd += [
        # threads 2 (VPS 4 core): sisakan core untuk web server — dengan
        # threads=4 ffmpeg menyita seluruh CPU → web lag/blank saat render.
        "-c:v", "libx264", "-preset", "medium", "-crf", "18",
        "-threads", "2",
        "-pix_fmt", "yuv420p",
        "-c:a", "aac", "-b:a", "128k", "-ar", "44100",
        "-ac", "2",
        "-movflags", "+faststart",
        "-metadata", "comment=Made with CortexClip AI",
        out_path,
    ]
    run_ffmpeg(cmd)
    return out_path


def render_preview_fast(
    src: str,
    start: float,
    end: float,
    out_path: str,
    width: int = 270,
    height: int = 480,
    on_progress=None,
    camera_trajectory: Optional[list[float]] = None,
    camera_cuts: Optional[list[int]] = None,
    camera_fps: float = 15.0,
    camera_rolls: Optional[list[float]] = None,
) -> str:
    """Preview KILAT: potong + reframe 9:16 + transkode ultrafast.

    Tanpa watermark, tanpa subtitle (browser yang menampilkan subtitle live
    overlay). 270x480 CRF30 → klip 60 detik selesai ±3-6 detik di CPU 4 core.

    camera_trajectory: kalau diberikan, dipakai crop dinamis mengikuti wajah
    pembicara — SAMA seperti hasil unduhan. Tanpa ini preview memakai crop
    tengah dan framing preview berbeda dari hasil akhir (dulu memang begitu,
    dan user melihatnya sebagai "face tracking tidak jalan di preview").

    on_progress(pct): dipanggil dengan kemajuan NYATA dari ffmpeg (0-100) supaya
    UI bisa menampilkan persen, bukan layar hitam tanpa keterangan.
    """
    w, h = width, height
    src_w, src_h = probe_size(src)
    aspect = w / h
    vf_parts: list[str] = []
    cmdfile: Optional[str] = None
    if camera_trajectory and len(camera_trajectory) > 1:
        cmdfile = build_sendcmd_file(camera_trajectory, src_w, src_h,
                                    analysis_fps=camera_fps, cuts=camera_cuts,
                                    rolls=camera_rolls)
        crop_w = min(int(src_h * ASPECT), src_w)
        vf_parts.append(f"sendcmd=f={cmdfile}")
        # deroll juga di preview: kalau hanya hasil unduhan yang diluruskan,
        # framing preview dan hasil akhir berbeda (user menilainya "masih miring")
        if camera_rolls:
            vf_parts.append("rotate=a=0:c=none:ow=iw:oh=ih:bilinear=1")
        vf_parts.append(f"crop=w={crop_w}:h={src_h}:x=0:y=0")
    elif src_w / src_h > aspect:
        crop_w = int(src_h * aspect)
        vf_parts.append(f"crop=w={crop_w}:h={src_h}:x=(iw-ow)/2:y=0")
    else:
        crop_h = int(src_w / aspect)
        vf_parts.append(f"crop=w={src_w}:h={crop_h}:x=0:y=(ih-oh)/2")
    vf_parts.append(f"scale={w}:{h}:force_original_aspect_ratio=increase")
    vf_parts.append(f"crop={w}:{h}")

    pre: list[str] = ["ffmpeg", "-y", "-v", "error"]
    # sumber HTTP (video besar di storage): jangan mati karena putus sesaat,
    # dan seek pakai HTTP Range supaya tidak menarik seluruh file
    if src.startswith("http"):
        pre += ["-reconnect", "1", "-reconnect_streamed", "1",
                "-reconnect_delay_max", "5", "-rw_timeout", "30000000"]

    cmd = pre + [
        "-ss", f"{start:.3f}", "-t", f"{end - start:.3f}", "-i", src,
        "-vf", ",".join(vf_parts),
        "-c:v", "libx264", "-preset", "ultrafast", "-crf", "30",
        # VPS 4 core: sisakan CPU untuk web server (bukan 4 = web jadi blank)
        "-threads", "2",
        "-pix_fmt", "yuv420p",
        # coba copy audio (instan); kalau codec tak kompatibel ffmpeg error → caller retry
        "-c:a", "aac", "-b:a", "96k",
        "-movflags", "+faststart",
        out_path,
    ]
    if on_progress is not None:
        run_ffmpeg_progress(cmd, end - start, on_progress, timeout=600)
    else:
        run_ffmpeg(cmd, timeout=600)
    return out_path




def burn_hook_overlay(
    src: str,
    hook_text: str,
    out_path: str,
    position: str = "top",
    fontsize_ratio: float = 0.055,
) -> str:
    """Burn AI-generated hook text onto video using ffmpeg drawtext.
    
    Args:
        src: input video path
        hook_text: hook text to burn
        out_path: output video path
        position: "top" or "bottom"
        fontsize_ratio: font size as fraction of video height
    """
    if not hook_text or not hook_text.strip():
        shutil.copy2(src, out_path)
        return out_path
    
    # Escape special chars for drawtext
    escaped = hook_text.replace("\\", "\\\\") \
                       .replace(":", "\\:") \
                       .replace("'", "\\'") \
                       .replace("%", "\\%") \
                       .replace(",", "\\,") \
                       .replace("[", "\\[") \
                       .replace("]", "\\]")
    
    x = "(w-text_w)/2"
    y = "h*0.06" if position == "top" else "h-text_h-h*0.04"
    
    drawtext = (
        f"drawtext=text='{escaped}':x={x}:y={y}:"
        f"fontsize=h*{fontsize_ratio}:"
        f"fontcolor=white:borderw=4:bordercolor=black:"
        f"fontfile=/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
    )
    
    cmd = [
        "ffmpeg", "-y", "-v", "error",
        "-i", src,
        "-vf", drawtext,
        "-c:a", "copy",
        "-c:v", "libx264", "-preset", "medium", "-crf", "18",
        "-pix_fmt", "yuv420p",
        "-movflags", "+faststart",
        out_path,
    ]
    run_ffmpeg(cmd)
    return out_path

